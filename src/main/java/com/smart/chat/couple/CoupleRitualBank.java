    /** 按天+空间稳定取甜蜜任务（同一天同人同一任务）。 */
    public static String pickTask(String spaceId, String taskDay, String username) {
        return TASKS.get(Math.floorMod(stableHash(spaceId + "|" + taskDay + "|" + username), TASKS.size()));
    }

    /** 按天+空间稳定取默契题（同一天双方同一题，未答完前不换题）。 */
