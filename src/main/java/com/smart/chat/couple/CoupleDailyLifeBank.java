    /** 今日主题曲：按 space+day 稳定。 */
    public static Song pickSong(String spaceId, String day) {
        return SONGS.get(Math.floorMod(CoupleRitualBank.stableHash(spaceId + "|song|" + day), SONGS.size()));
    }

    /** 今日三条夸夸：按 space+day 稳定。 */
    public static List<String> pickPraises(String spaceId, String day) {
        long hash = CoupleRitualBank.stableHash(spaceId + "|praise|" + day);
        List<String> result = new java.util.ArrayList<>(3);
        for (int i = 0; i < 3; i++) {
            result.add(PRAISES.get(Math.floorMod(hash >> (i * 16), PRAISES.size())));
        }
        return result;
    }

    /** 今日接头暗号：按 space+day 稳定。 */
    public static String pickCodeword(String spaceId, String day) {
        return CODEWORDS.get(Math.floorMod(CoupleRitualBank.stableHash(spaceId + "|code|" + day), CODEWORDS.size()));
    }
