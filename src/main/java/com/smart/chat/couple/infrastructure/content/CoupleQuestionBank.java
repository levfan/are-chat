    /** 当日题号：按空间 + 日期稳定，跨平台一致（用同一把 FNV-1a 哈希）。 */
    public static int indexOf(String spaceId, String day) {
        return Math.floorMod(CoupleRitualBank.stableHash(spaceId + "|" + SALT + "|" + day), QUESTIONS.size());
    }

    /** 按题号取题干。 */
    public static String textAt(int index) {
        if (index < 0 || index >= QUESTIONS.size()) {
            return QUESTIONS.get(0);
        }
        return QUESTIONS.get(index);
    }

    /** 当日题目（空间 + 日期）。 */
    public static String[] pick(String spaceId, String day) {
        int index = indexOf(spaceId, day);
        return new String[]{String.valueOf(index), textAt(index)};
    }

