-- 依据：docs/couple-trim-ranking.md（174 张功能卡留 50 删 124）与其第九节进度账。
-- 口径：
--   1) 只删整模块清零、或模块内定向删后已无任何实体引用的表；
--      判据是「db/V*.sql 建过的 couple_* 表」减去「现存实体 @TableName 集合」，
--      不手写清单——实体↔Mapper↔表在本项目是精确 1:1，且 297 个 Mapper 无一条手写
--      SQL 联外表，所以没有实体就等于没有读写方。
--   2) 不做数据迁移、不建备份表：本次是产品裁剪，被删功能的数据随之作废。
--      生产库执行前另行手动备份，脚本本身不带备份逻辑。
--   3) 用 DROP TABLE IF EXISTS：MariaDB 10.11 与 H2 MODE=MySQL 都认，且新库存量走
--      baseline-on-migrate 会全量重放 V1→V50，脚本必须幂等。
--   4) 明确保留 couple_point_ledger：积分台账由 V27（生活经营所）建表，但该模块已删，
--      台账本身要留给周年抽奖箱的奖池与三个赚分入口（好事簿/家务轮盘/刮刮乐）。
-- 统计：db 建过的 couple_* 表 297 张，现存实体 117 个，本脚本 drop 193 张。
-- ============================================================================

